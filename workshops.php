         <p>The visual art of photography, apart from being a means of self-expression and communication, lends itself well as a mindful meditative practice.</p>
         <p>By creating a space to be fully attuned to our inner experience of the visual elements, photography can promote a state of mindfulness that cultivates a more expansive sense of self through extending the boundaries of our awareness and sensitivity.  With the emphasis less on the subject being photographed and more on the way the subject is experienced/seen, there is greater openness to letting the image speak to us in a meaningful way.  Moreover, seeing beyond the surface appearance of things through mindful reflection can inspire within us a greater sense of connection, toward a more authentic way of seeing and being in the world.</p>
         <p>This experiential workshop offers a reflective and interactive place to explore the medium of photography as a mindful meditative practice.  By honoring such attitudes as non-judgment, openness and receptivity, a safe environment will be provided for image-taking, reflection and discussion.</p>
